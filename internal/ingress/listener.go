package ingress

import (
	"net"
	"sync"
)

// LimitListener bounds accepted sockets, including incomplete TLS handshakes,
// idle keep-alive connections and hijacked protocol streams.
func LimitListener(listener net.Listener, capacity int) net.Listener {
	if capacity < 1 {
		panic("listener capacity must be positive")
	}
	return &limitedListener{Listener: listener, slots: make(chan struct{}, capacity), done: make(chan struct{})}
}

type limitedListener struct {
	net.Listener
	slots chan struct{}
	done  chan struct{}
	once  sync.Once
}

func (l *limitedListener) Accept() (net.Conn, error) {
	select {
	case l.slots <- struct{}{}:
	case <-l.done:
		return nil, net.ErrClosed
	}
	conn, err := l.Listener.Accept()
	if err != nil {
		<-l.slots
		return nil, err
	}
	return &limitedConn{Conn: conn, release: func() { <-l.slots }}, nil
}

func (l *limitedListener) Close() error {
	var err error
	l.once.Do(func() {
		close(l.done)
		err = l.Listener.Close()
	})
	return err
}

type limitedConn struct {
	net.Conn
	release func()
	once    sync.Once
}

func (c *limitedConn) Close() error {
	err := c.Conn.Close()
	c.once.Do(c.release)
	return err
}
